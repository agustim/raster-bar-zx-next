#!/usr/bin/env python3
"""Generate the raster-bar data files for the Spectrum Next.

Emits (into this same directory):
  gradient.inc  - BAND metallic shades, 8-bit NextReg $41 format (RRRGGGBB)
  copper.inc    - the full copper program bytes (WAIT/MOVE/HALT)
  targets.inc   - copper-memory byte offset of each band WAIT's Y (vertical) byte,
                  index k corresponds to bar line (T + k), k = 0..BAND inclusive
                  (last entry is the "end bar -> background" wait)

The bar is a rigid horizontal metallic band of BAND scanlines. The Copper paints
a different shade per scanline; only the vertical line coordinates are rewritten
each frame (by the IM2 handler) to translate the bar. No per-frame copper
re-upload is needed, and everything is hardware scanline-synchronised, so it is
stable on HDMI.
"""
import math

BAND = 32                    # bar height in scanlines
BAR_TOP0 = 90                # initial bar top scanline (must match rasterbar.asm)
BG = (0, 0, 0)               # background rgb (0..7 each)
FLOOR = (2, 2, 1)            # dim steel floor so the whole bar width is visible
PEAK = (6, 7, 3)             # centre highlight (steel-white); B limited to 3 in 8-bit


def to_nextreg41(r, g, b):
    """Encode a colour into the single byte written to NextReg $41 (RRRGGGBB)."""
    return ((r & 0x07) << 5) | ((g & 0x07) << 2) | (b & 0x03)


def shade_byte(k):
    """Metallic shade for band line k (0..BAND-1) as a NextReg $41 byte."""
    pos = k / (BAND - 1)
    env = math.sin(math.pi * pos)          # 0..1..0 specular envelope
    r = FLOOR[0] + (PEAK[0] - FLOOR[0]) * env
    g = FLOOR[1] + (PEAK[1] - FLOOR[1]) * env
    b = FLOOR[2] + (PEAK[2] - FLOOR[2]) * env
    r = int(round(min(7, max(0, r))))
    g = int(round(min(7, max(0, g))))
    b = int(round(min(7, max(0, b))))
    return to_nextreg41(r, g, b)


# ---- copper instruction builders -------------------------------------------
def c_wait(hor, ver):
    hi = 0x80 | ((hor // 8) & 0x1F) << 1 | ((ver >> 8) & 0x01)
    lo = ver & 0xFF
    return [hi & 0xFF, lo & 0xFF]


def c_move(reg, val):
    return [(reg & 0x7F) & 0xFF, val & 0xFF]


def c_halt():
    return [0xFF, 0xFF]


def build_copper(T0):
    """Build the copper list for a bar whose top scanline is T0.

    Offsets of the band WAIT Y bytes are returned as a side table.
    """
    prog = []
    targets = []
    prog += c_wait(0, 0)
    prog += c_move(0x43, 0x90)      # L2 first palette, no auto-increment
    prog += c_move(0x40, 0x00)      # palette index 0
    prog += c_move(0x41, to_nextreg41(*BG))
    for k in range(BAND):
        wait = c_wait(0, T0 + k)
        # the Y byte is the LSB (2nd byte) of the WAIT instruction
        targets.append(len(prog) + 1)
        prog += wait
        prog += c_move(0x41, shade_byte(k))
    # after the band, return to background so lines below stay dark
    targets.append(len(prog) + 1)
    prog += c_wait(0, T0 + BAND)
    prog += c_move(0x41, to_nextreg41(*BG))
    prog += c_halt()
    return bytes(prog), targets


def main():
    T0 = BAR_TOP0              # initial bar top (must match rasterbar.asm)
    copper, targets = build_copper(T0)

    with open("gradient.inc", "w") as f:
        f.write("; gradient.inc - generated by gen_gradient.py\n")
        f.write(f"; {BAND} metallic shades, NextReg $41 (RRRGGGBB) format\n")
        f.write("BandShades:\n")
        for k in range(BAND):
            f.write(f"\tDB ${shade_byte(k):02x}\t; k={k:2d}\n")
        f.write(f"BandShadesEnd:\n")
        f.write(f"BAND = {BAND}\n")

    with open("copper.inc", "w") as f:
        f.write("; copper.inc - generated by gen_gradient.py\n")
        f.write(f"; {len(copper)//2} copper instructions ({len(copper)} bytes)\n")
        f.write("CopperList:\n")
        for i in range(0, len(copper), 16):
            chunk = copper[i:i + 16]
            f.write("\tDB " + ",".join(f"${b:02x}" for b in chunk) + "\n")
        f.write("CopperListEnd:\n")

    with open("targets.inc", "w") as f:
        f.write("; targets.inc - generated by gen_gradient.py\n")
        f.write(f"; band WAIT Y-byte offsets; entry k = bar line (T + k), k=0..BAND\n")
        f.write("BandTargets:\n")
        for k in range(0, len(targets), 16):
            chunk = targets[k:k + 16]
            f.write("\tDB " + ",".join(f"${v:02x}" for v in chunk) + "\n")
        f.write("BandTargetsEnd:\n")

    print(f"wrote gradient.inc ({BAND} shades), copper.inc ({len(copper)} bytes), "
          f"targets.inc ({len(targets)} offsets)")


if __name__ == "__main__":
    main()
